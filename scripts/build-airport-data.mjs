/**
 * Regenerates the tables under src/data.
 *
 * Sources:
 *  - FAA Aeronautical Information Services "US Airport" feature layer, the only
 *    source of the two that carries an authoritative public/private-use flag.
 *  - OurAirports runways.csv and airport-frequencies.csv, for the runway
 *    environment and radio frequencies.
 *  - A pre-simplified US state boundary GeoJSON, for the map outline.
 *
 * Run with: pnpm data:build
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { mkdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const DATA_DIR = resolve(ROOT, 'src/data')
/** Raw airspace pulls are kept here so a re-run does not repay the rate limit. */
const CACHE_DIR = resolve(ROOT, '.cache')
const ARCGIS = 'https://services6.arcgis.com/ssFJjBXIUyZDrSYZ/arcgis/rest/services'
const FAA_LAYER = `${ARCGIS}/US_Airport/FeatureServer/0/query`
const RUNWAYS_CSV = 'https://davidmegginson.github.io/ourairports-data/runways.csv'
const FREQUENCIES_CSV =
  'https://davidmegginson.github.io/ourairports-data/airport-frequencies.csv'
const STATES_GEOJSON =
  'https://raw.githubusercontent.com/PublicaMundi/MappingAPI/master/data/geojson/us-states.json'
const CLASS_AIRSPACE_LAYER = `${ARCGIS}/Class_Airspace/FeatureServer/0/query`
const SUA_LAYER = `${ARCGIS}/Special_Use_Airspace/FeatureServer/0/query`
/**
 * The airspace layers meter by returned vertex, not by request, and these
 * polygons are dense. Small pages with a pause between them stay under the quota;
 * a 429 is still handled, it just costs a minute.
 */
const AIRSPACE_PAGE = 50
const AIRSPACE_PACE_MS = 8_000

/** Minimal RFC-4180 parser; the source files quote embedded commas. */
function parseCsv(text) {
  const rows = []
  let row = []
  let field = ''
  let quoted = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quoted) {
      if (c !== '"') field += c
      else if (text[i + 1] === '"') (field += '"'), i++
      else quoted = false
    } else if (c === '"') quoted = true
    else if (c === ',') (row.push(field), (field = ''))
    else if (c === '\n') (row.push(field), rows.push(row), (row = []), (field = ''))
    else if (c !== '\r') field += c
  }
  if (field || row.length) (row.push(field), rows.push(row))
  return rows
}

async function fetchCsv(url) {
  const rows = parseCsv(await (await fetch(url)).text())
  const head = rows[0]
  const col = (name) => {
    const index = head.indexOf(name)
    if (index < 0) throw new Error(`${url} is missing column ${name}`)
    return index
  }
  return { rows: rows.slice(1), col }
}

async function publicUseAirports() {
  const features = []
  for (let offset = 0; ; offset += 1000) {
    const params = new URLSearchParams({
      where: "PRIVATEUSE=0 AND TYPE_CODE='AD' AND COUNTRY='UNITED STATES'",
      outFields: 'IDENT,ICAO_ID,NAME,SERVCITY,STATE,ELEVATION,OPERSTATUS,MIL_CODE,IAPEXISTS',
      returnGeometry: 'true',
      outSR: '4326',
      f: 'json',
      resultOffset: String(offset),
      resultRecordCount: '1000',
    })
    const page = await (await fetch(`${FAA_LAYER}?${params}`)).json()
    if (!page.features?.length) break
    features.push(...page.features)
    if (page.features.length < 1000) break
  }
  return features
}

/** "SAN CARLOS" -> "San Carlos", leaving directional abbreviations capitalised. */
function titleCase(s) {
  return s
    .toLowerCase()
    .replace(/\b[a-z]/g, (c) => c.toUpperCase())
    .replace(/\b(Us|Ne|Nw|Se|Sw)\b/g, (w) => w.toUpperCase())
}

/**
 * Free-text columns go through this. The tables are pipe-delimited with one row
 * per line and the decoders are plain `split`, so a delimiter inside a name or a
 * label would shift every field after it. Upstream data has none today; this
 * keeps a future refresh from silently corrupting a row.
 */
function text(value) {
  return (value ?? '').replace(/[|\r\n]+/g, ' ').trim()
}

function writeTable(file, header, rows) {
  writeFileSync(
    resolve(DATA_DIR, `${file}.generated.ts`),
    `// Generated by scripts/build-airport-data.mjs. Do not edit.\n` +
      `// ${rows.length} rows. ${header}\n` +
      `export const ${file.toUpperCase().replace(/-/g, '_')}_TABLE = ${JSON.stringify(rows.join('\n'))}\n`,
  )
  console.log(`${file}: ${rows.length} rows`)
}

await mkdir(DATA_DIR, { recursive: true })

// ---------------------------------------------------------------- airports

const PAVED = /ASP|CON|PEM|BIT|TAR|COP/

const runwayCsv = await fetchCsv(RUNWAYS_CSV)
const runwaysByIdent = new Map()
for (const row of runwayCsv.rows) {
  const ident = row[runwayCsv.col('airport_ident')]
  if (!ident || row[runwayCsv.col('closed')] === '1') continue
  const list = runwaysByIdent.get(ident) ?? []
  list.push({
    le: row[runwayCsv.col('le_ident')] ?? '',
    he: row[runwayCsv.col('he_ident')] ?? '',
    len: Number.parseInt(row[runwayCsv.col('length_ft')] || '0', 10) || 0,
    width: Number.parseInt(row[runwayCsv.col('width_ft')] || '0', 10) || 0,
    surface: (row[runwayCsv.col('surface')] || '').toUpperCase(),
    lit: row[runwayCsv.col('lighted')] === '1',
    heading: Number.parseFloat(row[runwayCsv.col('le_heading_degT')] || ''),
  })
  runwaysByIdent.set(ident, list)
}

const frequencyCsv = await fetchCsv(FREQUENCIES_CSV)
/**
 * Types a pilot needs to plan an arrival. Approach and centre sectors are left
 * out because they are regional rather than a property of the field.
 */
const FREQUENCY_TYPES = new Set([
  'CTAF', 'UNIC', 'TWR', 'GND', 'CLD', 'ATIS', 'AWOS', 'ASOS', 'AFIS',
])
const frequenciesByIdent = new Map()
for (const row of frequencyCsv.rows) {
  const ident = row[frequencyCsv.col('airport_ident')]
  const type = row[frequencyCsv.col('type')]
  const mhz = Number.parseFloat(row[frequencyCsv.col('frequency_mhz')] || '')
  // 108 to 137 MHz covers VHF comms plus the nav band some AWOS sites use.
  if (!ident || !FREQUENCY_TYPES.has(type) || !(mhz >= 108 && mhz <= 137)) continue
  const list = frequenciesByIdent.get(ident) ?? []
  list.push({ type, mhz, label: (row[frequencyCsv.col('description')] || '').trim() })
  frequenciesByIdent.set(ident, list)
}

/** OurAirports keys on ICAO where one exists, and on a K-prefixed FAA id otherwise. */
function lookup(map, id, icao) {
  return map.get(icao) ?? map.get(id) ?? map.get(`K${id}`)
}

const airportRows = []
const runwayRows = []
const frequencyRows = []

for (const { attributes: a, geometry: g } of await publicUseAirports()) {
  if (!g || typeof g.x !== 'number' || typeof g.y !== 'number') continue
  if (a.OPERSTATUS !== 'OPERATIONAL') continue
  const id = (a.IDENT ?? '').trim()
  if (!id) continue
  const icao = (a.ICAO_ID ?? '').trim()

  const runways = (lookup(runwaysByIdent, id, icao) ?? [])
    .filter((r) => /^\d/.test(r.le))
    .sort((x, y) => y.len - x.len)
  const longest = runways[0]

  // Bit flags keep the encoded table small: 1 approach, 2 military, 4 paved, 8 lighted.
  const flags =
    (a.IAPEXISTS === 1 ? 1 : 0) |
    (a.MIL_CODE !== 'CIVIL' ? 2 : 0) |
    (longest && PAVED.test(longest.surface) ? 4 : 0) |
    (longest?.lit ? 8 : 0)

  airportRows.push(
    [
      id,
      icao === `K${id}` ? '' : icao, // the common KXXX case is reconstructed on load
      text(a.NAME),
      titleCase(text(a.SERVCITY)),
      text(a.STATE),
      Math.round(g.y * 1e5) / 1e5,
      Math.round(g.x * 1e5) / 1e5,
      a.ELEVATION == null ? '' : Math.round(a.ELEVATION),
      flags,
      longest?.len || '',
    ].join('|'),
  )

  for (const runway of runways) {
    // True bearings are surveyed for most fields. Where they are missing, fall
    // back to the runway number, which is magnetic and so only an approximation.
    const surveyed = Number.isFinite(runway.heading)
    const heading = surveyed
      ? Math.round(runway.heading) % 360
      : (Number.parseInt(runway.le, 10) * 10) % 360
    if (!Number.isFinite(heading)) continue
    // 1 lighted, 2 heading approximated from the runway number, 4 hard surface.
    const runwayFlags =
      (runway.lit ? 1 : 0) | (surveyed ? 0 : 2) | (PAVED.test(runway.surface) ? 4 : 0)
    runwayRows.push(
      [id, text(runway.le), text(runway.he), runway.len || '', runway.width || '', heading, runwayFlags].join('|'),
    )
  }

  for (const frequency of lookup(frequenciesByIdent, id, icao) ?? []) {
    frequencyRows.push(
      [id, frequency.type, frequency.mhz.toFixed(3), text(frequency.label)].join('|'),
    )
  }
}

airportRows.sort()
runwayRows.sort()
frequencyRows.sort()

writeTable('airports', 'id|icao|name|city|state|lat|lon|elev|flags|runwayFt', airportRows)
writeTable('runways', 'airportId|leIdent|heIdent|lengthFt|widthFt|headingTrue|flags', runwayRows)
writeTable('frequencies', 'airportId|type|mhz|label', frequencyRows)


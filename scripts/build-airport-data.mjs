/** Minimal RFC-4180 parser; the source files quote embedded commas. */
function parseCsv(text) {
  const rows = []
  let row = []
  let field = ''
  let quoted = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quoted) {
      if (c !== '"') field += c
      else if (text[i + 1] === '"') (field += '"'), i++
      else quoted = false
    } else if (c === '"') quoted = true
    else if (c === ',') (row.push(field), (field = ''))
    else if (c === '\n') (row.push(field), rows.push(row), (row = []), (field = ''))
    else if (c !== '\r') field += c
  }
  if (field || row.length) (row.push(field), rows.push(row))
  return rows
}

async function fetchCsv(url) {
  const rows = parseCsv(await (await fetch(url)).text())
  const head = rows[0]
  const col = (name) => {
    const index = head.indexOf(name)
    if (index < 0) throw new Error(`${url} is missing column ${name}`)
    return index
  }
  return { rows: rows.slice(1), col }
}

async function publicUseAirports() {
  const features = []
  for (let offset = 0; ; offset += 1000) {
    const params = new URLSearchParams({
      where: "PRIVATEUSE=0 AND TYPE_CODE='AD' AND COUNTRY='UNITED STATES'",
      outFields: 'IDENT,ICAO_ID,NAME,SERVCITY,STATE,ELEVATION,OPERSTATUS,MIL_CODE,IAPEXISTS',
      returnGeometry: 'true',
      outSR: '4326',
      f: 'json',
      resultOffset: String(offset),
      resultRecordCount: '1000',
    })
    const page = await (await fetch(`${FAA_LAYER}?${params}`)).json()
    if (!page.features?.length) break
    features.push(...page.features)
    if (page.features.length < 1000) break
  }
  return features
}

/** "SAN CARLOS" -> "San Carlos", leaving directional abbreviations capitalised. */
function titleCase(s) {
  return s
    .toLowerCase()
    .replace(/\b[a-z]/g, (c) => c.toUpperCase())
    .replace(/\b(Us|Ne|Nw|Se|Sw)\b/g, (w) => w.toUpperCase())
}

/**
 * Free-text columns go through this. The tables are pipe-delimited with one row
 * per line and the decoders are plain `split`, so a delimiter inside a name or a
 * label would shift every field after it. Upstream data has none today; this
 * keeps a future refresh from silently corrupting a row.
 */
function text(value) {
  return (value ?? '').replace(/[|\r\n]+/g, ' ').trim()
}


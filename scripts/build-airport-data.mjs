const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

/** Pages an ArcGIS layer, backing off when the service meters us. */
async function fetchAirspace(url, where, outFields, cacheFile) {
  const cachePath = resolve(CACHE_DIR, cacheFile)
  if (existsSync(cachePath)) {
    console.log(`  reusing ${cacheFile}; delete it to re-download`)
    return JSON.parse(readFileSync(cachePath, 'utf8'))
  }
  const features = []
  for (let offset = 0; ; offset += AIRSPACE_PAGE) {
    const params = new URLSearchParams({
      where,
      outFields,
      returnGeometry: 'true',
      outSR: '4326',
      f: 'json',
      geometryPrecision: '4',
      resultOffset: String(offset),
      resultRecordCount: String(AIRSPACE_PAGE),
    })
    let page
    for (let attempt = 0; attempt < 6 && !page; attempt++) {
      const body = await (await fetch(`${url}?${params}`)).json()
      if (body.error?.code === 429) {
        console.log('  rate limited, pausing 65s')
        await sleep(65_000)
        continue
      }
      if (body.error) throw new Error(JSON.stringify(body.error))
      page = body
    }
    if (!page?.features?.length) break
    features.push(...page.features)
    process.stdout.write(`\r  ${features.length} areas`)
    if (page.features.length < AIRSPACE_PAGE) break
    await sleep(AIRSPACE_PACE_MS)
  }
  process.stdout.write('\n')
  await mkdir(CACHE_DIR, { recursive: true })
  writeFileSync(cachePath, JSON.stringify(features))
  return features
}

/**
 * Douglas-Peucker on a lon/lat ring. Longitude is scaled by the cosine of the
 * ring's latitude so the tolerance means roughly the same distance everywhere.
 */
function simplifyRing(ring, toleranceDeg) {
  if (ring.length < 4) return ring
  const meanLat = ring.reduce((sum, [, lat]) => sum + lat, 0) / ring.length
  const kx = Math.cos((meanLat * Math.PI) / 180)
  const keep = new Uint8Array(ring.length)
  keep[0] = 1
  keep[ring.length - 1] = 1

  const stack = [[0, ring.length - 1]]
  while (stack.length) {
    const [first, last] = stack.pop()
    if (last - first < 2) continue
    const ax = ring[first][0] * kx
    const ay = ring[first][1]
    const bx = ring[last][0] * kx
    const by = ring[last][1]
    const dx = bx - ax
    const dy = by - ay
    const lengthSq = dx * dx + dy * dy

    let worst = -1
    let worstIndex = -1
    for (let i = first + 1; i < last; i++) {
      const px = ring[i][0] * kx
      const py = ring[i][1]
      let distSq
      if (lengthSq === 0) {
        distSq = (px - ax) ** 2 + (py - ay) ** 2
      } else {
        const t = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / lengthSq))
        distSq = (px - (ax + t * dx)) ** 2 + (py - (ay + t * dy)) ** 2
      }
      if (distSq > worst) {
        worst = distSq
        worstIndex = i
      }
    }

    if (worst > toleranceDeg * toleranceDeg) {
      keep[worstIndex] = 1
      stack.push([first, worstIndex], [worstIndex, last])
    }
  }
  return ring.filter((_, i) => keep[i] === 1)
}

/** Thousandths of a degree, about 60 metres, delta encoded. */
function encodeRing(ring) {
  let lastLon = 0
  let lastLat = 0
  const parts = []
  for (const [lon, lat] of ring) {
    const x = Math.round(lon * 1000)
    const y = Math.round(lat * 1000)
    if (parts.length && x === lastLon && y === lastLat) continue
    parts.push(`${x - lastLon},${y - lastLat}`)
    lastLon = x
    lastLat = y
  }
  return parts
}

/** Feet MSL, or null for a surface floor or a bound the source cannot express. */
function altitude(value, code, uom) {
  if (code === 'SFC' || code === 'GND') return null
  if (uom !== 'FT' || typeof value !== 'number' || value <= 0) return null
  return Math.round(value)
}

/**
 * Tolerance scales with the size of the area, so a four-mile Class D circle stays
 * round while a restricted area spanning a degree is not stored vertex by vertex.
 */
function ringTolerance(ring) {
  let minLon = Infinity
  let minLat = Infinity
  let maxLon = -Infinity
  let maxLat = -Infinity
  for (const [lon, lat] of ring) {
    if (lon < minLon) minLon = lon
    if (lon > maxLon) maxLon = lon
    if (lat < minLat) minLat = lat
    if (lat > maxLat) maxLat = lat
  }
  const half = Math.max(maxLon - minLon, maxLat - minLat) / 2
  return Math.max(0.0006, Math.min(0.006, half * 0.012))
}


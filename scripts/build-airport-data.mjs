const PAVED = /ASP|CON|PEM|BIT|TAR|COP/

const runwayCsv = await fetchCsv(RUNWAYS_CSV)
const runwaysByIdent = new Map()
for (const row of runwayCsv.rows) {
  const ident = row[runwayCsv.col('airport_ident')]
  if (!ident || row[runwayCsv.col('closed')] === '1') continue
  const list = runwaysByIdent.get(ident) ?? []
  list.push({
    le: row[runwayCsv.col('le_ident')] ?? '',
    he: row[runwayCsv.col('he_ident')] ?? '',
    len: Number.parseInt(row[runwayCsv.col('length_ft')] || '0', 10) || 0,
    width: Number.parseInt(row[runwayCsv.col('width_ft')] || '0', 10) || 0,
    surface: (row[runwayCsv.col('surface')] || '').toUpperCase(),
    lit: row[runwayCsv.col('lighted')] === '1',
    heading: Number.parseFloat(row[runwayCsv.col('le_heading_degT')] || ''),
  })
  runwaysByIdent.set(ident, list)
}

const frequencyCsv = await fetchCsv(FREQUENCIES_CSV)
/**
 * Types a pilot needs to plan an arrival. Approach and centre sectors are left
 * out because they are regional rather than a property of the field.
 */
const FREQUENCY_TYPES = new Set([
  'CTAF', 'UNIC', 'TWR', 'GND', 'CLD', 'ATIS', 'AWOS', 'ASOS', 'AFIS',
])
const frequenciesByIdent = new Map()
for (const row of frequencyCsv.rows) {
  const ident = row[frequencyCsv.col('airport_ident')]
  const type = row[frequencyCsv.col('type')]
  const mhz = Number.parseFloat(row[frequencyCsv.col('frequency_mhz')] || '')
  // 108 to 137 MHz covers VHF comms plus the nav band some AWOS sites use.
  if (!ident || !FREQUENCY_TYPES.has(type) || !(mhz >= 108 && mhz <= 137)) continue
  const list = frequenciesByIdent.get(ident) ?? []
  list.push({ type, mhz, label: (row[frequencyCsv.col('description')] || '').trim() })
  frequenciesByIdent.set(ident, list)
}

/** OurAirports keys on ICAO where one exists, and on a K-prefixed FAA id otherwise. */
function lookup(map, id, icao) {
  return map.get(icao) ?? map.get(id) ?? map.get(`K${id}`)
}

const airportRows = []
const runwayRows = []
const frequencyRows = []

for (const { attributes: a, geometry: g } of await publicUseAirports()) {
  if (!g || typeof g.x !== 'number' || typeof g.y !== 'number') continue
  if (a.OPERSTATUS !== 'OPERATIONAL') continue
  const id = (a.IDENT ?? '').trim()
  if (!id) continue
  const icao = (a.ICAO_ID ?? '').trim()

  const runways = (lookup(runwaysByIdent, id, icao) ?? [])
    .filter((r) => /^\d/.test(r.le))
    .sort((x, y) => y.len - x.len)
  const longest = runways[0]

  // Bit flags keep the encoded table small: 1 approach, 2 military, 4 paved, 8 lighted.
  const flags =
    (a.IAPEXISTS === 1 ? 1 : 0) |
    (a.MIL_CODE !== 'CIVIL' ? 2 : 0) |
    (longest && PAVED.test(longest.surface) ? 4 : 0) |
    (longest?.lit ? 8 : 0)

  airportRows.push(
    [
      id,
      icao === `K${id}` ? '' : icao, // the common KXXX case is reconstructed on load
      text(a.NAME),
      titleCase(text(a.SERVCITY)),
      text(a.STATE),
      Math.round(g.y * 1e5) / 1e5,
      Math.round(g.x * 1e5) / 1e5,
      a.ELEVATION == null ? '' : Math.round(a.ELEVATION),
      flags,
      longest?.len || '',
    ].join('|'),
  )

  for (const runway of runways) {
    // True bearings are surveyed for most fields. Where they are missing, fall
    // back to the runway number, which is magnetic and so only an approximation.
    const surveyed = Number.isFinite(runway.heading)
    const heading = surveyed
      ? Math.round(runway.heading) % 360
      : (Number.parseInt(runway.le, 10) * 10) % 360
    if (!Number.isFinite(heading)) continue
    // 1 lighted, 2 heading approximated from the runway number, 4 hard surface.
    const runwayFlags =
      (runway.lit ? 1 : 0) | (surveyed ? 0 : 2) | (PAVED.test(runway.surface) ? 4 : 0)
    runwayRows.push(
      [id, text(runway.le), text(runway.he), runway.len || '', runway.width || '', heading, runwayFlags].join('|'),
    )
  }

  for (const frequency of lookup(frequenciesByIdent, id, icao) ?? []) {
    frequencyRows.push(
      [id, frequency.type, frequency.mhz.toFixed(3), text(frequency.label)].join('|'),
    )
  }
}

airportRows.sort()
runwayRows.sort()
frequencyRows.sort()

writeTable('airports', 'id|icao|name|city|state|lat|lon|elev|flags|runwayFt', airportRows)
